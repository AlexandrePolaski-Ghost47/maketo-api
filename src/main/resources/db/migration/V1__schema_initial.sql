CREATE TABLE utilisateur (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(80)  NOT NULL,
    prenom            VARCHAR(80)  NOT NULL,
    telephone         VARCHAR(20)  NOT NULL UNIQUE,
    whatsapp          VARCHAR(20),
    matricule         VARCHAR(30)  NOT NULL UNIQUE,
    filiere           VARCHAR(100),
    niveau            VARCHAR(20),
    mot_de_passe      VARCHAR(100) NOT NULL,
    role              VARCHAR(20)  NOT NULL DEFAULT 'ETUDIANT'
                      CHECK (role IN ('ETUDIANT', 'ADMIN')),
    statut            VARCHAR(20)  NOT NULL DEFAULT 'EN_ATTENTE'
                      CHECK (statut IN ('EN_ATTENTE', 'ACTIF', 'BLOQUE')),
    pro_expire_le     TIMESTAMPTZ,
    solde_credits     INTEGER      NOT NULL DEFAULT 0 CHECK (solde_credits >= 0),
    version           BIGINT       NOT NULL DEFAULT 0,
    date_inscription  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    date_modification TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE categorie (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom             VARCHAR(60) NOT NULL UNIQUE,
    slug            VARCHAR(60) NOT NULL UNIQUE,
    icone           VARCHAR(50),
    ordre_affichage INTEGER     NOT NULL DEFAULT 0,
    actif           BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE annonce (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendeur_id                  BIGINT        NOT NULL REFERENCES utilisateur(id),
    categorie_id                BIGINT        NOT NULL REFERENCES categorie(id),
    titre                       VARCHAR(100)  NOT NULL,
    description                 VARCHAR(2000),
    prix                        INTEGER       CHECK (prix >= 0),
    prix_a_debattre             BOOLEAN       NOT NULL DEFAULT FALSE,
    etat                        VARCHAR(20)   NOT NULL CHECK (etat IN ('NEUF', 'OCCASION')),
    lieu                        VARCHAR(100),
    formule                     VARCHAR(20)   NOT NULL CHECK (formule IN ('GRATUITE', 'PRO')),
    statut                      VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE'
                                CHECK (statut IN ('ACTIVE', 'VENDUE', 'EXPIREE', 'SUPPRIMEE')),
    boost_jusqu_a               TIMESTAMPTZ,
    nb_vues                     INTEGER       NOT NULL DEFAULT 0,
    nb_contacts                 INTEGER       NOT NULL DEFAULT 0,
    nb_renouvellements          INTEGER       NOT NULL DEFAULT 0,
    date_creation               TIMESTAMPTZ   NOT NULL DEFAULT now(),
    date_dernier_renouvellement TIMESTAMPTZ,
    date_expiration             TIMESTAMPTZ   NOT NULL,
    date_modification           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_prix CHECK (prix IS NOT NULL OR prix_a_debattre = TRUE)
);

CREATE INDEX idx_annonce_statut_expiration ON annonce (statut, date_expiration);
CREATE INDEX idx_annonce_categorie_statut  ON annonce (categorie_id, statut);
CREATE INDEX idx_annonce_vendeur           ON annonce (vendeur_id);
CREATE INDEX idx_annonce_boost             ON annonce (boost_jusqu_a) WHERE boost_jusqu_a IS NOT NULL;

CREATE TABLE photo_annonce (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annonce_id BIGINT       NOT NULL REFERENCES annonce(id) ON DELETE CASCADE,
    url        VARCHAR(500) NOT NULL,
    public_id  VARCHAR(200) NOT NULL,          -- identifiant Cloudinary (pour suppression)
    ordre      SMALLINT     NOT NULL,
    CONSTRAINT uk_photo_ordre UNIQUE (annonce_id, ordre)
);

CREATE TABLE favori (
    utilisateur_id BIGINT      NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
    annonce_id     BIGINT      NOT NULL REFERENCES annonce(id) ON DELETE CASCADE,
    date_ajout     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (utilisateur_id, annonce_id)
);

CREATE TABLE signalement (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annonce_id      BIGINT       NOT NULL REFERENCES annonce(id),
    auteur_id       BIGINT       NOT NULL REFERENCES utilisateur(id),
    motif           VARCHAR(30)  NOT NULL
                    CHECK (motif IN ('ARNAQUE', 'INTERDIT', 'DOUBLON', 'INAPPROPRIE', 'AUTRE')),
    commentaire     VARCHAR(500),
    statut          VARCHAR(20)  NOT NULL DEFAULT 'OUVERT' CHECK (statut IN ('OUVERT', 'TRAITE')),
    traite_par      BIGINT       REFERENCES utilisateur(id),
    date_creation   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    date_traitement TIMESTAMPTZ,
    CONSTRAINT uk_signalement UNIQUE (annonce_id, auteur_id)   -- un seul signalement par personne
);

CREATE TABLE offre (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(30)  NOT NULL UNIQUE,
    libelle      VARCHAR(100) NOT NULL,
    type         VARCHAR(20)  NOT NULL CHECK (type IN ('BOOST', 'ABONNEMENT')),
    prix         INTEGER      NOT NULL CHECK (prix >= 0),
    duree_heures INTEGER      NOT NULL CHECK (duree_heures > 0),
    actif        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE transaction_credit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT      NOT NULL REFERENCES utilisateur(id),
    type           VARCHAR(20) NOT NULL
                   CHECK (type IN ('RECHARGE', 'BOOST', 'ABONNEMENT_PRO', 'BONUS', 'REMBOURSEMENT')),
    montant        INTEGER     NOT NULL CHECK (montant <> 0),
    solde_apres    INTEGER     NOT NULL CHECK (solde_apres >= 0),
    offre_id       BIGINT      REFERENCES offre(id),
    annonce_id     BIGINT      REFERENCES annonce(id),
    reference_momo VARCHAR(50) UNIQUE,         -- empêche de créditer deux fois le même paiement
    valide_par     BIGINT      REFERENCES utilisateur(id),
    date_creation  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_transaction_utilisateur ON transaction_credit (utilisateur_id, date_creation DESC);

CREATE TABLE parametre (
    cle               VARCHAR(60)  PRIMARY KEY,
    valeur            VARCHAR(255) NOT NULL,
    description       VARCHAR(255),
    date_modification TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE refresh_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT      NOT NULL REFERENCES utilisateur(id) ON DELETE CASCADE,
    token_hash     VARCHAR(64) NOT NULL UNIQUE,  -- SHA-256 : le jeton brut n'est jamais stocké
    expire_le      TIMESTAMPTZ NOT NULL,
    revoque        BOOLEAN     NOT NULL DEFAULT FALSE,
    date_creation  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_refresh_token_utilisateur ON refresh_token (utilisateur_id);
