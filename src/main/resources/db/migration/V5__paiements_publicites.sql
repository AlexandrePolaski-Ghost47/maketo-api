-- =========================================================
-- Paiements Mobile Money (recharges du portefeuille) + publicités
-- =========================================================

CREATE TABLE paiement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id    BIGINT       NOT NULL REFERENCES utilisateur(id),
    reference         VARCHAR(50)  NOT NULL UNIQUE,     -- notre identifiant (transactionUniqueID chez CT Pay)
    process_code      VARCHAR(100) UNIQUE,              -- identifiant chez le fournisseur
    fournisseur       VARCHAR(20)  NOT NULL,
    operateur         VARCHAR(20)  NOT NULL,
    telephone         VARCHAR(20)  NOT NULL,
    montant           INTEGER      NOT NULL CHECK (montant > 0),
    frais             INTEGER,
    statut            VARCHAR(20)  NOT NULL DEFAULT 'EN_ATTENTE'
                      CHECK (statut IN ('EN_ATTENTE', 'REUSSI', 'ECHOUE')),
    message_erreur    VARCHAR(255),
    date_creation     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    date_finalisation TIMESTAMPTZ
);

CREATE INDEX idx_paiement_statut_date      ON paiement (statut, date_creation);
CREATE INDEX idx_paiement_utilisateur_date ON paiement (utilisateur_id, date_creation DESC);

-- Un paiement ne peut créditer le portefeuille qu'UNE seule fois (garantie au niveau de la base)
ALTER TABLE transaction_credit ADD COLUMN paiement_id BIGINT UNIQUE REFERENCES paiement(id);

CREATE TABLE publicite (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annonceur     VARCHAR(100) NOT NULL,
    titre         VARCHAR(100),
    image_url     VARCHAR(500) NOT NULL,
    image_id      VARCHAR(200) NOT NULL,
    lien          VARCHAR(500),
    date_debut    DATE         NOT NULL,
    date_fin      DATE         NOT NULL,
    actif         BOOLEAN      NOT NULL DEFAULT TRUE,
    nb_clics      INTEGER      NOT NULL DEFAULT 0,
    date_creation TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_publicite_dates CHECK (date_fin >= date_debut)
);

